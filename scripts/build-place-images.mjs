// Regenerates lib/place-images.ts from whatever is sitting in public/places/.
// The photos are static files in the repo, so the database does not need a
// column for them — the id is the filename, and this manifest is what lets a
// card know whether a photo exists instead of rendering a broken <img>.
// It maps id -> path because the originals are stored in their source format
// (jpg or png) rather than re-encoded; next/image handles the conversion.
// Run after adding or removing files: node scripts/build-place-images.mjs
import { readdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../public/places/', import.meta.url);
const entries = readdirSync(dir)
  .filter(f => /\.(jpg|jpeg|png)$/i.test(f))
  .sort()
  .map(f => [f.replace(/\.(jpg|jpeg|png)$/i, ''), `/places/${f}`]);

writeFileSync(new URL('../lib/place-images.ts', import.meta.url),
  `// Generated by scripts/build-place-images.mjs — do not edit by hand.\n` +
  `export const PLACE_IMAGES: Record<string, string> = {\n` +
  entries.map(([id, src]) => `  '${id}': '${src}',`).join('\n') +
  `\n};\n`);

console.log(`place-images.ts: ${entries.length} photos`);
